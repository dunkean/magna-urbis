import { describe, expect, it } from 'vitest';
import { defaultSettings } from '../src/v2/settings';
import { regionalPopulation } from '../src/v2/regionalPopulation';
import { clearRegionalPopulation, editRegionalPopulation, followEnvironmentPopulation } from '../src/v2/regionalPopulationEdits';
import { encodeCityCode, decodeCityCode } from '../src/v2/cityCode';

describe('regional population controls', () => {
  it('restores automatic sizes after a saved large local population and pinned counts', () => {
    const s = defaultSettings();
    s.extent = 40000;
    const automatic = regionalPopulation(s);
    s.local = { main: { population: 40000, culture: 'medina' }, 'village-0': { population: 45000 } };
    s.region = { demography: { population: 85000, counts: { city: 1, town: 0, village: 0, hamlet: 0, farmstead: 0 }, followCulture: false } };
    followEnvironmentPopulation(s);
    expect(s.local.main).toEqual({ culture: 'medina' });
    expect(s.local['village-0'].population).toBeUndefined();
    const reset = regionalPopulation(s);
    expect(reset.places.map(p => p.population)).toEqual(automatic.places.map(p => p.population));
    expect(reset.counts).toEqual(automatic.counts);
    expect(reset.places.every(p => p.population <= 20000)).toBe(true);
  });
  it('pins only the class being edited instead of freezing every displayed count', () => {
    const s = defaultSettings();
    s.extent = 40000;
    editRegionalPopulation(s, 'village', 3);
    expect(s.region?.demography?.counts).toEqual({ village: 3 });
    editRegionalPopulation(s, 'hamlet', 0);
    expect(s.region?.demography?.counts).toEqual({ village: 3, hamlet: 0 });
    editRegionalPopulation(s, 'village', undefined);
    expect(s.region?.demography?.counts).toEqual({ hamlet: 0 });
  });
  it('resizes the places when population changes, keeping their number and the fixed counts', () => {
    const s = defaultSettings();
    s.extent = 40000;
    s.options.culture = 'european-organic';
    s.terrain!.climate = 'temperate';
    s.terrain!.relief = 'flat';
    s.region = { demography: { density: 2, counts: { village: 3 }, followCulture: false } };
    const before = regionalPopulation(s);
    editRegionalPopulation(s, 'population', 10000);
    const small = regionalPopulation(s);
    expect(s.region.demography).toEqual({ population: 10000, counts: { village: 3 }, followCulture: false });
    expect(small.places).toHaveLength(before.places.length);
    expect(small.density).toBe(10000 / 1600);
    editRegionalPopulation(s, 'population', 100000);
    const large = regionalPopulation(s);
    expect(large.places).toHaveLength(before.places.length);
    expect(large.counts.village).toBe(3);
    expect(large.allocatedPopulation).toBe(100000);
    expect(large.density).toBe(100000 / 1600);
    expect(regionalPopulation(decodeCityCode(encodeCityCode(s)).settings)).toEqual(large);
  });
  it('adds the inhabitants of an added place to a typed population', () => {
    const s = defaultSettings();
    s.extent = 10000;
    s.options.culture = 'european-organic';
    s.terrain!.climate = 'temperate';
    s.terrain!.relief = 'flat';
    editRegionalPopulation(s, 'population', 7000);
    const before = regionalPopulation(s);
    editRegionalPopulation(s, 'town', before.counts.town + 1);
    expect(s.region?.demography?.population).toBe(7000 + before.classSizes.town);
    const after = regionalPopulation(s);
    expect(after.counts.town).toBe(before.counts.town + 1);
    expect(after.allocatedPopulation).toBe(7000 + before.classSizes.town);
    editRegionalPopulation(s, 'town', undefined);
    expect(s.region?.demography?.population).toBe(7000);
  });
  it('uses the most recently edited density instead of keeping the previous explicit population', () => {
    const s = defaultSettings();
    s.extent = 10000;
    editRegionalPopulation(s, 'population', 100000);
    editRegionalPopulation(s, 'density', 100);
    expect(s.region?.demography?.population).toBeUndefined();
    expect(regionalPopulation(s).population).toBe(10000);
    editRegionalPopulation(s, 'population', 20000);
    expect(s.region?.demography?.density).toBeUndefined();
    expect(regionalPopulation(s).density).toBe(200);
  });
  it('returns a manual list to automatic distribution and lets isolated density control its count', () => {
    const s = defaultSettings();
    s.region = { placement: { list: [{ key: 'main', name: 'Pinned', population: 100, culture: 'elven', siteType: 'auto', sitePrefs: {} }] }, demography: { isolatedCount: 99 } };
    editRegionalPopulation(s, 'population', 5000);
    expect(s.region.placement).toEqual({ mode: 'auto' });
    editRegionalPopulation(s, 'isolatedCount', 99);
    editRegionalPopulation(s, 'isolatedDensity', 0);
    expect(s.region.demography?.isolatedCount).toBeUndefined();
    expect(regionalPopulation(s).isolatedCount).toBe(0);
  });
  it('"None" empties the region and "Follow the environment" restores the automatic list', () => {
    const s = defaultSettings();
    s.extent = 10000;
    const automatic = regionalPopulation(s);
    s.region = { demography: { density: 5, counts: { town: 3 }, followCulture: false }, placement: { mode: 'list', counts: { village: 2 }, list: [{ key: 'main', name: 'Pinned', population: 100, culture: 'elven', siteType: 'auto', sitePrefs: {} }] } };
    clearRegionalPopulation(s);
    const none = regionalPopulation(s);
    expect(none.places).toEqual([]);
    expect(none.population).toBe(0);
    expect(none.isolatedCount).toBe(0);
    expect(Object.values(none.counts).every(n => n === 0)).toBe(true);
    editRegionalPopulation(s, 'village', 1);
    expect(regionalPopulation(s).places).toHaveLength(1);
    followEnvironmentPopulation(s);
    expect(s.region.demography).toEqual({ followCulture: false });
    expect(s.region.placement).toEqual({ mode: 'auto' });
    expect(regionalPopulation(s)).toEqual(automatic);
  });
});

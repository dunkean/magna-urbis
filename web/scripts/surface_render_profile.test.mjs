import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { applySurfaceRenderProfile, loadSurfaceRenderProfile, validateSurfaceRenderProfile } from './surface_render_profile.mjs';

const repository = fileURLToPath(new URL('../../', import.meta.url));
const definition = path.join(repository, 'viewer-local/profiles/surface-v2.json');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const write = (filename, value) => { mkdirSync(path.dirname(filename), { recursive: true }); writeFileSync(filename, typeof value === 'object' ? JSON.stringify(value) : value); };
function fixture(t, platform = 'win32') {
  const parent = path.join(repository, 'web/out/surface/render-profile-tests'); mkdirSync(parent, { recursive: true });
  const root = mkdtempSync(path.join(parent, 'fixture-'));
  // This directory is generated by this test beneath its declared output root.
  t.after(() => { assert.ok(path.resolve(root).startsWith(path.resolve(parent) + path.sep)); rmSync(root, { recursive: true, force: true }); });
  mkdirSync(path.join(root, 'viewer-local/profiles'), { recursive: true }); copyFileSync(definition, path.join(root, 'viewer-local/profiles/surface-v2.json'));
  const profile = loadSurfaceRenderProfile('surface-v2', { root, platform });
  const materials = { materials: [{ id: 'test-soil', maps: Object.fromEntries(['baseColor', 'normal', 'roughness', 'height'].map(role => [role, { path: 'map.bin' }])) }] };
  write(profile.defaults.assets, materials); write(path.join(path.dirname(profile.defaults.assets), 'map.bin'), 'authored-test-pbr-file');
  const vegetation = { format: 'magna-vegetation-assets', version: 1, assets: [{ family: 'grass', product: { path: 'mesh.json' }, sources: Object.fromEntries(['baseColor', 'normal', 'arm', 'alpha'].map(role => [role, { path: `${role}.bin` }])) }] };
  write(profile.defaults.vegetationAssets, vegetation); write(path.join(path.dirname(profile.defaults.vegetationAssets), 'mesh.json'), '{}');
  for (const role of ['baseColor', 'normal', 'arm', 'alpha']) write(path.join(path.dirname(profile.defaults.vegetationAssets), `${role}.bin`), 'authored-test-grass-file');
  const geometry = 'authored-test-geometry-not-renderable', geometryHash = hash(geometry);
  const trees = { format: 'magna-tree-render-assets', version: 1, digest: profile.metadata.requiredTreeDigest, sourceGeometry: { path: 'tree.glb', sha256: geometryHash }, mask: { path: 'mask.a8' }, lookup: { path: 'lookup.f32' }, albedoEncodingCorrection: { source16bitRGBExact: true, alphaNormalizedValuesExact: true, allOriginalBinBytesRetained: true, geometryAccessorsMeshesUVNormalsTangentsMaterialsUnchanged: true, outputGlbSha256: geometryHash }, views: Array.from({ length: 5 }, (_, i) => ({ name: `view${i}`, products: { color: { path: `color${i}.rgbah` }, normal: { path: `normal${i}.rgbah` } } })) };
  write(profile.defaults.treeAssets, trees); const directory = path.dirname(profile.defaults.treeAssets);
  for (const filename of ['mask.a8', 'lookup.f32', ...trees.views.flatMap(view => Object.values(view.products).map(item => item.path))]) write(path.join(directory, filename), 'authored-test-product');
  write(path.join(directory, 'tree.glb'), geometry); write(profile.defaults.heightBatch, 'not-an-executable-no-engine-test');
  return { root, profile, materials, trees, directory, options: { root, platform, cwd: root } };
}

test('explicit surface-v2 resolves fixed paths and metadata without scanning caches', t => {
  const f = fixture(t), profile = f.profile;
  assert.equal(profile.defaults.heightBatch, path.join(f.root, 'viewer-local/native-height/target/release/magna-surface-height-batch.exe'));
  assert.equal(profile.defaults.treeAssets, path.join(f.root, 'web/out/vegetation-tree-v14/resolved.json'));
  assert.equal(profile.metadata.profileSha256, hash(readFileSync(definition)));
  assert.equal(profile.defaults.presentation, 'aerial'); assert.equal(profile.defaults.waterMode, 'source-map'); assert.equal(profile.defaults.waterVectorTint, 'uniform');
  assert.equal(profile.defaults.waterSymbolWidthPx, 1.25); assert.equal(profile.defaults.nativeLogMode, 'threaded');
  const result = applySurfaceRenderProfile(['--world', 'source.surfacebin', '--render-profile', 'surface-v2'], f.options);
  assert.ok(!result.args.includes('--render-profile'));
  assert.equal(result.profile.metadata.treeEncodingCorrectionVerified, true);
  assert.equal(result.profile.metadata.runtimeFileCount, 23); // Four manifests/exe, one PBR file, five grass files, thirteen tree files.
  assert.match(result.profile.metadata.effectiveSha256, /^[a-f0-9]{64}$/);
});

test('platform executable mapping is explicit', t => {
  const f = fixture(t, 'linux');
  assert.ok(f.profile.defaults.heightBatch.endsWith('magna-surface-height-batch'));
  assert.ok(!f.profile.defaults.heightBatch.endsWith('.exe'));
});

test('caller overrides win; relative paths keep caller meaning and unused defaults need not exist', t => {
  const f = fixture(t), caller = path.join(f.root, 'caller'); mkdirSync(caller);
  const maps = Object.fromEntries(Object.entries(f.materials.materials[0].maps).map(([role]) => [role, { path: path.relative(caller, path.join(path.dirname(f.profile.defaults.assets), 'map.bin')) }]));
  write(path.join(caller, 'override.json'), { materials: [{ id: 'caller-soil', maps }] });
  unlinkSync(f.profile.defaults.assets);
  const input = ['--render-profile', 'surface-v2', '--assets', 'caller/override.json', '--presentation', 'cartographic', '--top', '--water-symbol-width-px', '0'];
  const result = applySurfaceRenderProfile(input, f.options);
  assert.equal(result.args[result.args.indexOf('--assets') + 1], 'caller/override.json');
  assert.equal(result.args[result.args.indexOf('--presentation') + 1], 'cartographic');
  assert.equal(result.profile.metadata.effectiveDefaults.assets, path.join(caller, 'override.json'));
  assert.equal(result.profile.metadata.effectiveDefaults.waterSymbolWidthPx, '0');
  assert.deepEqual(result.profile.metadata.overrides.sort(), ['assets', 'presentation', 'waterSymbolWidthPx']);
  assert.equal(input[0], '--render-profile'); // Caller array is not mutated.
});

test('legacy invocation never implicitly chooses or probes a profile', () => {
  const original = ['--world', 'old.surfacebin', '--presentation', 'cartographic', '--assets', 'old-cache/resolved.json'];
  const result = applySurfaceRenderProfile(original, { root: '/missing/repository', platform: 'win32' });
  assert.deepEqual(result, { args: original, profile: null });
  assert.notEqual(result.args, original);
});

test('invalid effective combinations fail instead of changing explicit options', t => {
  const f = fixture(t);
  for (const patch of [{ presentation: 'photo' }, { nativeLogMode: 'asynchronous' }, { waterMode: 'raster' }, { waterVectorTint: 'river-only' }, { waterSymbolWidthPx: 2 }, { waterSymbolWidthPx: '-.1' }, { waterSymbolWidthPx: 'NaN' }, { waterSymbolWidthPx: '0x1' }, { waterSymbolWidthPx: '' }, { waterMode: 'source-levels' }, { waterMode: 'source-levels', waterVectorTint: 'source-classes' }]) {
    assert.throws(() => validateSurfaceRenderProfile(f.profile, { defaults: { ...f.profile.defaults, ...patch } }), /Surface render profile:/);
  }
  const valid = validateSurfaceRenderProfile(f.profile, { defaults: { ...f.profile.defaults, waterMode: 'source-levels', waterVectorTint: 'source-classes', waterSymbolWidthPx: 0 } });
  assert.equal(valid.defaults.waterMode, 'source-levels');
});

test('missing runtime artifacts fail descriptively before any engine invocation', t => {
  const f = fixture(t);
  unlinkSync(path.join(f.directory, 'normal3.rgbah'));
  assert.throws(() => validateSurfaceRenderProfile(f.profile), /tree view3 normal is missing.*normal3\.rgbah/);
  const args = ['--render-profile', 'surface-v2', '--godot', 'MISSING-GODOT-NOT-TO-BE-STARTED', ...Object.entries({ assets: '--assets', vegetationAssets: '--vegetation-assets', treeAssets: '--tree-assets', heightBatch: '--height-batch' }).flatMap(([key, flag]) => [flag, f.profile.defaults[key]])];
  const child = spawnSync(process.execPath, [path.join(repository, 'web/scripts/surface_viewer.mjs'), ...args], { encoding: 'utf8', windowsHide: true, timeout: 10000 });
  assert.equal(child.status, 1); assert.match(child.stderr, /tree view3 normal is missing/);
  assert.doesNotMatch(child.stderr, /Expected pinned Godot|spawnSync|Install pinned Terrain3D/);
});

test('wrong tree encoding/digest or changed corrected geometry cannot silently use legacy assets', t => {
  const f = fixture(t);
  write(f.profile.defaults.treeAssets, { ...f.trees, digest: '0'.repeat(64) });
  assert.throws(() => validateSurfaceRenderProfile(f.profile), /corrected digest/);
  write(f.profile.defaults.treeAssets, { ...f.trees, albedoEncodingCorrection: { ...f.trees.albedoEncodingCorrection, source16bitRGBExact: false } });
  assert.throws(() => validateSurfaceRenderProfile(f.profile), /validated source-sRGB encoding correction/);
  write(f.profile.defaults.treeAssets, f.trees); write(path.join(f.directory, 'tree.glb'), 'wrong-tree');
  assert.throws(() => validateSurfaceRenderProfile(f.profile), /geometry SHA256 mismatch/);
});

test('explicit profile never runs automatic Terrain3D bootstrap/download', t => {
  const f = fixture(t, process.platform);
  const directory = path.join(f.root, 'web/scripts'); mkdirSync(directory, { recursive: true });
  for (const filename of ['surface_viewer.mjs', 'surface_render_profile.mjs']) copyFileSync(path.join(repository, 'web/scripts', filename), path.join(directory, filename));
  const child = spawnSync(process.execPath, [path.join(directory, 'surface_viewer.mjs'), '--render-profile', 'surface-v2', '--godot', 'NOT-STARTED'], { encoding: 'utf8', windowsHide: true, timeout: 10000 });
  assert.equal(child.status, 1); assert.match(child.stderr, /requires preinstalled pinned Terrain3D/);
  assert.match(child.stderr, /no runtime downloads/); assert.doesNotMatch(child.stderr, /Expected pinned Godot|spawnSync/);
});

test('missing binary, unknown profile and ambiguous flags are rejected', t => {
  const f = fixture(t); unlinkSync(f.profile.defaults.heightBatch);
  assert.throws(() => validateSurfaceRenderProfile(f.profile), /--height-batch is missing/);
  assert.throws(() => loadSurfaceRenderProfile('../cache', f.options), /unknown profile/);
  assert.throws(() => applySurfaceRenderProfile(['--render-profile'], f.options), /requires an explicit/);
  assert.throws(() => applySurfaceRenderProfile(['--render-profile', 'surface-v2', '--render-profile', 'surface-v2'], f.options), /only once/);
  assert.throws(() => applySurfaceRenderProfile(['--render-profile', 'surface-v2', '--assets', 'a', '--assets', 'b'], f.options), /duplicate --assets/);
});

// Builds the V2 bundled heightmap test library with our own Rust/WASM terrain engine (no browser).
// Usage (from the repository root): node web/scripts/v2_heightmap_library.mjs [--pkg rust/pkg/wasm] [--n 512]
// Output: web/src/v2/assets/heightmaps/<id>.png (16-bit grayscale, Magna Urbis tEXt metre range) + library.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { deflateSync } from 'node:zlib';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const arg = (name, fallback) => { const i = process.argv.indexOf('--' + name); return i >= 0 ? process.argv[i + 1] : fallback; };
const pkg = resolve(root, arg('pkg', 'rust/pkg/wasm'));
const n = Number(arg('n', '512'));
const out = resolve(root, 'web/src/v2/assets/heightmaps');
mkdirSync(out, { recursive: true });

const mod = await import(pathToFileURL(resolve(pkg, 'magna_urbis_wasm.js')).href);
await mod.default({ module_or_path: readFileSync(resolve(pkg, 'magna_urbis_wasm_bg.wasm')) });
const { TerrainEngine } = mod;

/** Coast bits follow the V2 compass order: N, NE, E, SE, S, SW, W, NW. */
const maps = [
  { id: 'alpine-massif', name: ['Alpine massif', 'Massif alpin'], relief: 'high-mountains', width: 12000, motif: 4000, coast: 0, seed: 'library-alpine-7' },
  { id: 'rolling-hills', name: ['Rolling hills', 'Collines ondulées'], relief: 'hills', width: 8000, motif: 3000, coast: 0, seed: 'library-hills-3' },
  { id: 'river-canyon', name: ['River canyon', 'Canyon fluvial'], relief: 'canyon', width: 10000, motif: 3000, coast: 0, seed: 'library-canyon-11' },
  { id: 'coastal-ranges', name: ['Coastal ranges', 'Chaînons côtiers'], relief: 'mixed', width: 16000, motif: 5000, coast: 1 | 2 | 4, mix: .45, seed: 'library-coast-5' },
  { id: 'mountain-island', name: ['Mountain island', 'Île montagneuse'], relief: 'mountains', width: 14000, motif: 4000, coast: 255, island: 'island', seed: 'library-island-2' },
  { id: 'high-plateau', name: ['High plateau', 'Haut plateau'], relief: 'plateau', width: 12000, motif: 4000, coast: 0, environment: 'hills', seed: 'library-plateau-9' },
];

const signature = Uint8Array.of(137, 80, 78, 71, 13, 10, 26, 10);
const crcTable = Uint32Array.from({ length: 256 }, (_, i) => { for (let k = 0; k < 8; k++) i = i & 1 ? 0xedb88320 ^ (i >>> 1) : i >>> 1; return i >>> 0; });
function chunk(name, data) {
  const buf = Buffer.alloc(data.length + 12); buf.writeUInt32BE(data.length, 0); buf.write(name, 4, 'latin1'); Buffer.from(data).copy(buf, 8);
  let crc = 0xffffffff; for (let i = 4; i < buf.length - 4; i++) crc = crcTable[(crc ^ buf[i]) & 255] ^ (crc >>> 8);
  buf.writeUInt32BE((crc ^ 0xffffffff) >>> 0, buf.length - 4); return buf;
}
/** Same container as web/src/ui/terrainHeightmap.ts heightmapPng: the tEXt range is read back exactly. */
function png16(heights, side, width) {
  let min = Infinity, max = -Infinity; for (const h of heights) { min = Math.min(min, h); max = Math.max(max, h); }
  const stride = side * 2 + 1, raw = Buffer.alloc(side * stride), range = max - min;
  for (let y = 0; y < side; y++) for (let x = 0; x < side; x++) raw.writeUInt16BE(range ? Math.round((heights[y * side + x] - min) / range * 65535) : 0, y * stride + 1 + x * 2);
  const header = Buffer.alloc(13); header.writeUInt32BE(side, 0); header.writeUInt32BE(side, 4); header[8] = 16;
  const meta = JSON.stringify({ min, max, width, units: 'm', seaLevel: 0, license: 'generated by Magna Urbis' });
  return { bytes: Buffer.concat([signature, chunk('IHDR', header), chunk('tEXt', Buffer.from('magna-urbis\0' + meta, 'latin1')), chunk('IDAT', deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]), min, max };
}

const library = { format: 'magna-urbis-heightmap-library', version: 1, generator: 'web/scripts/v2_heightmap_library.mjs (Rust TerrainEngine via WASM)', maps: [] };
for (const map of maps) {
  const t0 = performance.now();
  const engine = new TerrainEngine(map.seed, map.width, map.relief, 1, map.motif, map.mix ?? .5, map.environment ?? 'mixed');
  if (map.coast) engine.set_coast(map.coast, map.island ?? 'island');
  const sample = engine.sample_region(0, 0, map.width, n);
  const heights = sample.height; sample.free(); engine.free();
  const { bytes, min, max } = png16(heights, n, map.width);
  writeFileSync(resolve(out, `${map.id}.png`), bytes);
  library.maps.push({ id: map.id, file: `${map.id}.png`, name: { en: map.name[0], fr: map.name[1] }, relief: map.relief,
    size: [n, n], extentM: map.width, verticalRangeM: [Math.round(min * 10) / 10, Math.round(max * 10) / 10],
    seaLevelM: 0, seed: map.seed, coastMask: map.coast, license: 'generated by Magna Urbis' });
  console.log(`${map.id}: ${(performance.now() - t0).toFixed(0)} ms · ${min.toFixed(1)} → ${max.toFixed(1)} m · ${(bytes.length / 1024).toFixed(0)} KiB`);
}
writeFileSync(resolve(out, 'library.json'), JSON.stringify(library, null, 2) + '\n');

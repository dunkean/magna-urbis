interface Source { name: string; input: TerrainSketch; sketch: TerrainSketch; width?: number; range?: [number, number]; sizeEdited?: boolean }
let source: Source | undefined, produced: TerrainSketch | undefined;
const fit = { scale: 1, datum: 0, crop: 100, black: 0, white: 1200 };

export async function loadLibraryHeightmap(entry: LibraryEntry): Promise<import('../ui/terrainHeightmap').HeightmapFile> {
  const url = libraryUrl(entry); if (!url) throw new Error(`Missing library file ${entry.file}`);
  const response = await fetch(url); if (!response.ok) throw new Error(`${entry.file}: HTTP ${response.status}`);
  const file = new File([await response.blob()], entry.file, { type: 'image/png' });
  return readHeightmap(file, entry.verticalRangeM[0], entry.verticalRangeM[1]);
}

/** A sketch written by the importer or the editor becomes the new fit source. */
function capture(settings: V2Settings): void {
  // Recipes containing the former image input join the same metre-based fit path.
  if (settings.options.importedHeight) {
    const image = settings.options.importedHeight, loaded = imageHeightmap(image);
    if (loaded.elevationRange) {
      const black = -(settings.options.importSea ?? 0), white = (settings.options.heightScale ?? 1200) + black;
      loaded.terrain = fitHeightmap(loaded.terrain, { scale: 1, datum: 0, crop: 100, black, white }, loaded.elevationRange);
      loaded.elevationRange = [black, white];
    }
    acceptHeightmap(settings, loaded, image.name ?? translate('Imported heightmap'));
  }
  const sketch = settings.terrain?.sketch;
  if (!sketch?.processing || sketch === produced || sketch === source?.input) return;
  const imported = heightmapImport(sketch) ?? settings.terrain?.heightmap;
  source = { name: imported?.name ?? translate('Imported heightmap'), input: sketch,
    sketch: { ...sketch, heights: [...sketch.heights] }, width: imported?.width, range: imported?.elevationRange };
  fit.scale = 1; fit.datum = 0; fit.crop = 100;
  [fit.black, fit.white] = source.range ?? [0, 1200];
}
function applyFit(settings: V2Settings): void {
  if (!source) return;
  settings.terrain ??= {};
  produced = settings.terrain.sketch = fitHeightmap(source.sketch, fit, source.range);
  delete settings.terrain.sampleSpacing;
  // Saved recipes retain the fitted endpoints, so reopening still offers black/white editing.
  const fittedRange = source.range ? [fit.black, fit.white].map(h => Math.max(-12000, Math.min(12000, (h - fit.datum) * fit.scale))) as [number, number] : undefined;
  settings.terrain.heightmap = { name: source.name, width: source.width, elevationRange: fittedRange };
  rememberHeightmap(produced, { terrain: produced, width: source.width, elevationRange: fittedRange }, source.name);
}

export interface HeightmapSourceBindings {
  getSettings(): V2Settings;
  /** A heightmap became the relief input (library pick). */
  onLoaded(): void;
  importFile(): void;
  importImage(): void;
  onError(error: unknown): void;
}
/** Import actions and bundled heightmaps shared by the relief sidebar. */
export function mountHeightmapSource(host: HTMLElement, bindings: HeightmapSourceBindings): { sync(): void } {
  host.classList.add('heightmap-source');
  const actions = document.createElement('div'); actions.className = 'heightmap-actions';
  const file = document.createElement('button'); file.type = 'button'; file.id = 'heightmap-library-import'; file.append(iconImg('source-heightmap', 22)); const fileText = document.createElement('span'); setText(fileText, 'Import a heightmap…'); file.append(fileText); file.onclick = bindings.importFile;
  const image = document.createElement('button'); image.type = 'button'; image.className = 'quiet small'; setText(image, '8-bit image (JPEG, WebP)…'); image.onclick = bindings.importImage;
  actions.append(file, image);
  host.append(actions);
  const libraryHead = document.createElement('div'); libraryHead.className = 'heightmap-library-head'; setText(libraryHead, 'Test library');
  const library = document.createElement('div'); library.className = 'heightmap-library';
  const status = document.createElement('p'); status.className = 'hint'; status.setAttribute('role', 'status'); status.hidden = true; setText(status, 'Loading the heightmap…');
  const tiles = new Map<LibraryEntry, HTMLButtonElement>();
  let loading = false, selected: { entry: LibraryEntry; sketch: TerrainSketch } | undefined;
  for (const entry of HEIGHTMAP_LIBRARY) {
    registerMessages({ [entry.name.en]: entry.name });
    const tile = document.createElement('button'); tile.type = 'button'; tile.className = 'heightmap-tile'; tile.title = translate('Generated by Magna Urbis');
    const preview = document.createElement('img'); preview.src = libraryUrl(entry)!; preview.alt = ''; preview.loading = 'lazy';
    const name = document.createElement('span'); name.className = 'heightmap-name'; setText(name, entry.name.en);
    const range = document.createElement('small'); setDynamicText(range, () => entry.verticalRangeM.map(value => formatDistance(value, getDistanceUnit(), numberLocale())).join(' → '));
    tile.append(preview, name, range); tiles.set(entry, tile); library.append(tile);
    tile.onclick = async () => {
      if (loading || tile.disabled) return;
      const settings = bindings.getSettings(); loading = true; status.hidden = false; tile.setAttribute('aria-busy', 'true');
      try {
        const loaded = await loadLibraryHeightmap(entry);
        // A source/recipe change while loading must not replace the newly selected input.
        if (host.hidden || settings !== bindings.getSettings()) return;
        acceptHeightmap(settings, { ...loaded, width: loaded.width ?? entry.extentM }, translate(entry.name.en));
        selected = { entry, sketch: loaded.terrain }; capture(settings);
        host.dispatchEvent(new CustomEvent('relief-source-changed', { bubbles: true, detail: 'import' }));
        bindings.onLoaded();
      } catch (error) { bindings.onError(error); }
      finally { loading = false; status.hidden = true; tile.removeAttribute('aria-busy'); sync(); }
    };
  }
  host.append(libraryHead, library, status);
  function sync(): void {
    for (const [entry, tile] of tiles) tile.setAttribute('aria-pressed', String(selected?.entry === entry && bindings.getSettings().terrain?.sketch === selected.sketch));
  }
  return { sync };
}

export interface HeightmapFitBindings { getSettings(): V2Settings; onChange(): void; disabled?(): boolean }
/** Fit is applied to a retained copy of the loaded source, so it is reversible and exact. */
export function mountHeightmapFit(host: HTMLElement, bindings: HeightmapFitBindings): { sync(): void; quick: HTMLElement; summary: HTMLElement } {
  host.classList.add('heightmap-fit');
  const status = document.createElement('p'); status.className = 'hint heightmap-fit-status';
  const form = document.createElement('div'); form.className = 'parameter-form';
  const field = (label: string, key: keyof typeof fit, min: number, max: number, step: number): HTMLInputElement => {
    const row = document.createElement('label'); row.className = 'parameter-field parameter-number';
    const caption = document.createElement('span'); caption.className = 'parameter-caption'; setDynamicText(caption, () => key==='datum'||key==='black'||key==='white' ? `${translate(label).replace(/\s*[（(][^()（）]*[)）]\s*$/, '')} (${displayUnit('m',getDistanceUnit())})` : translate(label));
    const input = document.createElement('input'); input.type = 'number'; input.min = String(min); input.max = String(max); input.step = String(step); input.id = `heightmap-fit-${key}`;
    input.addEventListener('change', () => {
      const value = key==='datum'||key==='black'||key==='white' ? convertUnits(Number(input.value),displayUnit('m',getDistanceUnit()),'m') : Number(input.value), settings = bindings.getSettings();
      const minimum = key === 'crop' && source ? Math.max(min, Math.min(100, Math.ceil(Math.max(16, adaptedExtent(settings) / 1000) / source.sketch.resolution * 100))) : min;
      if (!input.value.trim() || !Number.isFinite(value) || value < minimum || value > max) { input.setAttribute('aria-invalid', 'true'); return; }
      input.removeAttribute('aria-invalid');
      fit[key] = value; applyFit(settings);
      bindings.onChange(); sync();
    });
    row.append(caption, input); form.append(row); return input;
  };
  const scale = field('Vertical scale ×', 'scale', .05, 10, .05), datum = field('Datum shift (m)', 'datum', -5000, 5000, 1), crop = field('Central crop (%)', 'crop', 25, 100, 1);
  const black = field('Elevation of black (m)', 'black', -12000, 12000, 1), white = field('Elevation of white (m)', 'white', -12000, 12000, 1);
  form.prepend(black.closest('label')!, white.closest('label')!);
  const hint = document.createElement('p'); hint.className = 'hint'; setText(hint, 'Values below 0 m become sea. Increasing the datum lowers the terrain.');
  const sizeNote = document.createElement('p'); sizeNote.className = 'hint'; setText(sizeNote, 'Size read from the file');
  // Size controls are moved between stage panels. Observe their edit events so
  // the provenance note disappears immediately, even before the next chain sync.
  const dismissSizeNote = (event: Event): void => {
    const target = event.target as HTMLElement | null;
    const selector = event.type === 'click' ? '[data-extent]'
      : '[data-setting-path="extent"], [data-slider-path="extent"], [data-field-path="terrain.sampleSpacing"]';
    if (!target?.closest?.(selector)) return;
    const sketch = bindings.getSettings().terrain?.sketch;
    if (!source || !sketch?.processing || (sketch !== source.input && sketch !== produced)) return;
    source.sizeEdited = true;
    sizeNote.hidden = true;
  };
  document.addEventListener('input', dismissSizeNote, true);
  document.addEventListener('change', dismissSizeNote, true);
  document.addEventListener('click', dismissSizeNote, true);
  const reset = document.createElement('button'); reset.type = 'button'; reset.className = 'small'; setText(reset, 'Restore the source');
  reset.onclick = () => { fit.scale = 1; fit.datum = 0; fit.crop = 100; [fit.black, fit.white] = source?.range ?? [0, 1200]; applyFit(bindings.getSettings()); bindings.onChange(); sync(); };
  const summary = document.createElement('div'); summary.className = 'heightmap-fit-summary'; summary.append(status, sizeNote);
  host.append(summary, form, hint, reset);
  // Collapsed-row access: the vertical scale, bound to the same fit model.
  const quick = document.createElement('label'); quick.className = 'parameter-field parameter-number quick-field';
  const quickCaption = document.createElement('span'); quickCaption.className = 'parameter-caption'; setText(quickCaption, 'Vertical scale ×');
  const quickInput = document.createElement('input'); quickInput.type = 'number'; quickInput.min = '.05'; quickInput.max = '10'; quickInput.step = '.05'; quickInput.id = 'heightmap-fit-scale-quick';
  quickInput.addEventListener('change', () => { scale.value = quickInput.value; scale.dispatchEvent(new Event('change')); });
  quick.append(quickCaption, quickInput);
  function sync(): void {
    const settings = bindings.getSettings(); capture(settings);
    const sketch = settings.terrain?.sketch, active = !!sketch?.processing && !!source;
    for (const input of [black, white, scale, datum, crop, quickInput]) input.disabled = !active || !!bindings.disabled?.();
    reset.disabled = !active || !!bindings.disabled?.();
    if (document.activeElement !== scale) scale.value = String(fit.scale);
    if (document.activeElement !== quickInput) quickInput.value = String(fit.scale);
    if (document.activeElement !== datum) datum.value = String(convertUnits(fit.datum,'m',displayUnit('m',getDistanceUnit())));
    if (document.activeElement !== crop) crop.value = String(fit.crop);
    crop.min = String(source ? Math.max(25, Math.min(100, Math.ceil(Math.max(16, adaptedExtent(settings) / 1000) / source.sketch.resolution * 100))) : 25);
    for (const [key, input] of [['black', black], ['white', white], ['datum', datum]] as const) {
      if (document.activeElement !== input) input.value = String(convertUnits(fit[key], 'm', displayUnit('m', getDistanceUnit())));
      input.min = String(convertUnits(key === 'datum' ? -5000 : -12000, 'm', displayUnit('m', getDistanceUnit())));
      input.max = String(convertUnits(key === 'datum' ? 5000 : 12000, 'm', displayUnit('m', getDistanceUnit()))); input.step = 'any';
    }
    black.closest('label')!.hidden = white.closest('label')!.hidden = !active || !source?.range;
    if (active && source && source.width !== settings.extent) source.sizeEdited = true;
    sizeNote.hidden = !active || source?.width === undefined || !!source.sizeEdited || source.width !== settings.extent;
    if (!active || !sketch) { setText(status, 'No heightmap loaded yet. Import one from the sidebar.'); return; }
    let lo = Infinity, hi = -Infinity; for (const h of sketch.heights) { lo = Math.min(lo, h); hi = Math.max(hi, h); }
    setDynamicText(status, () => `${source!.name} · ${sketch.resolution.toLocaleString(numberLocale())} × ${sketch.resolution.toLocaleString(numberLocale())} px · ${formatDistance(adaptedExtent(settings),getDistanceUnit(),numberLocale())} · ${convertUnits(adaptedExtent(settings) / sketch.resolution,'m',displayUnit('m',getDistanceUnit())).toLocaleString(numberLocale(), { maximumFractionDigits: 2 })} ${displayUnit('m',getDistanceUnit())}/px · ${formatDistance(lo,getDistanceUnit(),numberLocale())} → ${formatDistance(hi,getDistanceUnit(),numberLocale())}`);
  }
  registerMessages({ 'Imported heightmap': { en: 'Imported heightmap', fr: 'Heightmap importée' } });
  onUnitsChange(sync);
  sync(); return { sync, quick, summary };
}

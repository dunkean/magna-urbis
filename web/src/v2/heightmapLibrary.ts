interface Source { name: string; sketch: TerrainSketch; width?: number }
let source: Source | undefined, produced: TerrainSketch | undefined;
const fit = { scale: 1, datum: 0, crop: 100 };

export async function loadLibraryHeightmap(entry: LibraryEntry): Promise<{ terrain: TerrainSketch; width?: number }> {
  const url = libraryUrl(entry); if (!url) throw new Error(`Missing library file ${entry.file}`);
  const response = await fetch(url); if (!response.ok) throw new Error(`${entry.file}: HTTP ${response.status}`);
  const file = new File([await response.blob()], entry.file, { type: 'image/png' });
  return readHeightmap(file, entry.verticalRangeM[0], entry.verticalRangeM[1]);
}

/** A sketch written by the importer or the editor becomes the new fit source. */
function capture(settings: V2Settings, name?: string): void {
  const sketch = settings.terrain?.sketch;
  if (!sketch?.processing || sketch === produced || sketch === source?.sketch) return;
  source = { name: name ?? source?.name ?? translate('Imported heightmap'), sketch: { ...sketch, heights: [...sketch.heights] } };
  fit.scale = 1; fit.datum = 0; fit.crop = 100;
}
function applyFit(settings: V2Settings): void {
  if (!source) return;
  const n = source.sketch.resolution, crop = Math.max(.25, Math.min(1, fit.crop / 100)), offset = (1 - crop) / 2, heights = new Array<number>(n * n);
  const src = source.sketch.heights, sample = (x: number, y: number) => src[Math.min(n - 1, Math.max(0, y)) * n + Math.min(n - 1, Math.max(0, x))];
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
    const u = (offset + (x + .5) / n * crop) * n - .5, v = (offset + (y + .5) / n * crop) * n - .5, x0 = Math.floor(u), y0 = Math.floor(v), fx = u - x0, fy = v - y0;
    const h = (sample(x0, y0) * (1 - fx) + sample(x0 + 1, y0) * fx) * (1 - fy) + (sample(x0, y0 + 1) * (1 - fx) + sample(x0 + 1, y0 + 1) * fx) * fy;
    heights[y * n + x] = Math.max(-12000, Math.min(12000, (h - fit.datum) * fit.scale));
  }
  settings.terrain ??= {};
  produced = settings.terrain.sketch = { ...source.sketch, heights };
}


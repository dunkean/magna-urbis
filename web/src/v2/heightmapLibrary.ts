interface Source { name: string; sketch: TerrainSketch; width?: number }
let source: Source | undefined, produced: TerrainSketch | undefined;
const fit = { scale: 1, datum: 0, crop: 100 };

export async function loadLibraryHeightmap(entry: LibraryEntry): Promise<{ terrain: TerrainSketch; width?: number }> {
  const url = libraryUrl(entry); if (!url) throw new Error(`Missing library file ${entry.file}`);
  const response = await fetch(url); if (!response.ok) throw new Error(`${entry.file}: HTTP ${response.status}`);
  const file = new File([await response.blob()], entry.file, { type: 'image/png' });
  return readHeightmap(file, entry.verticalRangeM[0], entry.verticalRangeM[1]);
}

/** A sketch written by the importer or the editor becomes the new fit source. */
function capture(settings: V2Settings, name?: string): void {
  const sketch = settings.terrain?.sketch;
  if (!sketch?.processing || sketch === produced || sketch === source?.sketch) return;
  source = { name: name ?? source?.name ?? translate('Imported heightmap'), sketch: { ...sketch, heights: [...sketch.heights] } };
  fit.scale = 1; fit.datum = 0; fit.crop = 100;
}
function applyFit(settings: V2Settings): void {
  if (!source) return;
  const n = source.sketch.resolution, crop = Math.max(.25, Math.min(1, fit.crop / 100)), offset = (1 - crop) / 2, heights = new Array<number>(n * n);
  const src = source.sketch.heights, sample = (x: number, y: number) => src[Math.min(n - 1, Math.max(0, y)) * n + Math.min(n - 1, Math.max(0, x))];
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
    const u = (offset + (x + .5) / n * crop) * n - .5, v = (offset + (y + .5) / n * crop) * n - .5, x0 = Math.floor(u), y0 = Math.floor(v), fx = u - x0, fy = v - y0;
    const h = (sample(x0, y0) * (1 - fx) + sample(x0 + 1, y0) * fx) * (1 - fy) + (sample(x0, y0 + 1) * (1 - fx) + sample(x0 + 1, y0 + 1) * fx) * fy;
    heights[y * n + x] = Math.max(-12000, Math.min(12000, (h - fit.datum) * fit.scale));
  }
  settings.terrain ??= {};
  produced = settings.terrain.sketch = { ...source.sketch, heights };
}

export interface HeightmapSourceBindings {
  getSettings(): V2Settings;
  /** A heightmap became the relief input (library pick). */
  onLoaded(): void;
  importFile(): void;
  importImage(): void;
  onError(error: unknown): void;
}
/** Library grid + import buttons, shown inside Relief source when the heightmap alternative is chosen. */
export function mountHeightmapSource(host: HTMLElement, bindings: HeightmapSourceBindings): { sync(): void } {
  host.classList.add('heightmap-source');
  const intro = document.createElement('p'); intro.className = 'hint'; setText(intro, 'Choose a bundled heightmap or import your own (16-bit PNG or JSON keeps metres).');
  const actions = document.createElement('div'); actions.className = 'heightmap-actions';
  const file = document.createElement('button'); file.type = 'button'; file.id = 'heightmap-library-import'; file.append(iconImg('source-heightmap', 22)); const fileText = document.createElement('span'); setText(fileText, 'Import a heightmap…'); file.append(fileText); file.onclick = bindings.importFile;
  const image = document.createElement('button'); image.type = 'button'; image.className = 'quiet small'; setText(image, '8-bit image (JPEG, WebP)…'); image.onclick = bindings.importImage;
  actions.append(file, image);
  const head = document.createElement('div'); head.className = 'heightmap-library-head'; head.append(iconImg('source-library', 22)); const title = document.createElement('span'); setText(title, 'Test library'); head.append(title);
  const grid = document.createElement('div'); grid.className = 'heightmap-library'; grid.setAttribute('role', 'listbox'); grid.setAttribute('aria-label', translate('Test library'));
  const tiles = new Map<string, HTMLButtonElement>();
  for (const entry of HEIGHTMAP_LIBRARY) {
    const tile = document.createElement('button'); tile.type = 'button'; tile.className = 'heightmap-tile'; tile.setAttribute('role', 'option'); tile.dataset.heightmap = entry.id;
    const img = document.createElement('img'); img.src = libraryUrl(entry) ?? ''; img.alt = ''; img.loading = 'lazy';
    const caption = document.createElement('span'); caption.className = 'heightmap-name'; registerMessages({ [entry.name.en]: entry.name }); setText(caption, entry.name.en);
    const meta = document.createElement('small'); setDynamicText(meta, () => `${(entry.extentM / 1000).toLocaleString(numberLocale())} km · ${Math.round(entry.verticalRangeM[1] - entry.verticalRangeM[0]).toLocaleString(numberLocale())} m`);
    tile.title = `${entry.size[0]} × ${entry.size[1]} px · 16-bit · ${entry.license}`;
    tile.append(img, caption, meta);
    tile.onclick = async () => {
      tile.setAttribute('aria-busy', 'true');
      try {
        const { terrain, width } = await loadLibraryHeightmap(entry), settings = bindings.getSettings();
        settings.terrain ??= {}; delete settings.terrain.zones; delete settings.options.importedHeight;
        settings.terrain.sketch = terrain; if (width) settings.extent = width;
        capture(settings, getLanguage() === 'fr' ? entry.name.fr : entry.name.en); current = entry.id;
        bindings.onLoaded();
      } catch (error) { bindings.onError(error); } finally { tile.removeAttribute('aria-busy'); }
    };
    tiles.set(entry.id, tile); grid.append(tile);
  }
  let current: string | undefined;
  host.append(intro, actions, head, grid);
  return { sync() {
    const sketch = bindings.getSettings().terrain?.sketch;
    if (sketch !== produced && sketch !== source?.sketch && sketch?.processing) current = undefined;
    for (const [id, tile] of tiles) tile.setAttribute('aria-selected', String(id === current && !!sketch?.processing));
  } };
}

export interface HeightmapFitBindings { getSettings(): V2Settings; onChange(): void }
/** Fit is applied to a retained copy of the loaded source, so it is reversible and exact. */
export function mountHeightmapFit(host: HTMLElement, bindings: HeightmapFitBindings): { sync(): void; quick: HTMLElement } {
  host.classList.add('heightmap-fit');
  const status = document.createElement('p'); status.className = 'hint heightmap-fit-status';
  const form = document.createElement('div'); form.className = 'parameter-form';
  const field = (label: string, key: keyof typeof fit | 'width', min: number, max: number, step: number): HTMLInputElement => {
    const row = document.createElement('label'); row.className = 'parameter-field parameter-number';
    const caption = document.createElement('span'); caption.className = 'parameter-caption'; setText(caption, label);
    const input = document.createElement('input'); input.type = 'number'; input.min = String(min); input.max = String(max); input.step = String(step); input.id = `heightmap-fit-${key}`;
    input.addEventListener('change', () => {
      const value = Number(input.value), settings = bindings.getSettings();
      if (!Number.isFinite(value) || value < min || value > max) { input.setAttribute('aria-invalid', 'true'); return; }
      input.removeAttribute('aria-invalid');
      if (key === 'width') settings.extent = Math.round(value * 1000); else { fit[key] = value; applyFit(settings); }
      bindings.onChange(); sync();
    });
    row.append(caption, input); form.append(row); return input;
  };
  const scale = field('Vertical scale ×', 'scale', .05, 10, .05), datum = field('Datum shift (m)', 'datum', -5000, 5000, 1), crop = field('Central crop (%)', 'crop', 25, 100, 1), width = field('Map width (km)', 'width', .5, 100, .1);
  const hint = document.createElement('p'); hint.className = 'hint'; setText(hint, 'Raise the datum to flood low ground; values below 0 m become sea.');
  const reset = document.createElement('button'); reset.type = 'button'; reset.className = 'small'; setText(reset, 'Restore the source');
  reset.onclick = () => { fit.scale = 1; fit.datum = 0; fit.crop = 100; applyFit(bindings.getSettings()); bindings.onChange(); sync(); };
  host.append(status, form, hint, reset);
  // Collapsed-row access: the vertical scale, bound to the same fit model.
  const quick = document.createElement('label'); quick.className = 'parameter-field parameter-number quick-field';
  const quickCaption = document.createElement('span'); quickCaption.className = 'parameter-caption'; setText(quickCaption, 'Vertical scale ×');
  const quickInput = document.createElement('input'); quickInput.type = 'number'; quickInput.min = '.05'; quickInput.max = '10'; quickInput.step = '.05'; quickInput.id = 'heightmap-fit-scale-quick';
  quickInput.addEventListener('change', () => { scale.value = quickInput.value; scale.dispatchEvent(new Event('change')); });
  quick.append(quickCaption, quickInput);
  function sync(): void {
    const settings = bindings.getSettings(); capture(settings);
    const sketch = settings.terrain?.sketch, active = !!sketch?.processing && !!source;
    for (const input of [scale, datum, crop, quickInput]) input.disabled = !active;
    reset.disabled = !active;
    if (document.activeElement !== scale) scale.value = String(fit.scale);
    if (document.activeElement !== quickInput) quickInput.value = String(fit.scale);
    if (document.activeElement !== datum) datum.value = String(fit.datum);
    if (document.activeElement !== crop) crop.value = String(fit.crop);
    if (document.activeElement !== width) width.value = String((typeof settings.extent === 'number' ? settings.extent : 6000) / 1000);
    if (!active || !sketch) { setText(status, settings.options.importedHeight ? '8-bit image: use the height scale and sea level below.' : 'No heightmap loaded yet. Pick one in Relief source.'); return; }
    let lo = Infinity, hi = -Infinity; for (const h of sketch.heights) { lo = Math.min(lo, h); hi = Math.max(hi, h); }
    setDynamicText(status, () => `${source!.name} · ${sketch.resolution} × ${sketch.resolution} px · ${Math.round(lo).toLocaleString(numberLocale())} → ${Math.round(hi).toLocaleString(numberLocale())} m`);
  }
  registerMessages({ '8-bit image: use the height scale and sea level below.': { en: '8-bit image: use the height scale and sea level below.', fr: 'Image 8 bits : réglez l’échelle de hauteur et le niveau marin ci-dessous.' }, 'Imported heightmap': { en: 'Imported heightmap', fr: 'Heightmap importée' } });
  sync(); return { sync, quick };
}

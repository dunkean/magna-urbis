type Template = { pattern: RegExp; keys: string[]; target: string };
const numericSlots = new Set(['count', 'index', 'done', 'total', 'quarters', 'parcels', 'buildings', 'placed', 'built', 'population', 'extent', 'seconds', 'size', 'min', 'max', 'factor', 'status']);
const numberPattern = '[-+]?\\d[\\d \\u00a0\\u202f.,]*(?:[eE][-+]?\\d+)?';
function compileTemplate(source: string, target: string): Template {
  const keys: string[] = [];
  const token = /\{([a-zA-Z]+)\}/g;
  let start = 0, pattern = '';
  for (const match of source.matchAll(token)) {
    pattern += escapeRegex(source.slice(start, match.index));
    const capture = numericSlots.has(match[1]) ? numberPattern : match[1] === 'request' ? '(?:main/)?layout-[A-Za-z0-9:/_.-]+' : '[\\s\\S]+?';
    pattern += `(${capture})`; keys.push(match[1]); start = match.index! + match[0].length;
  }
  pattern += escapeRegex(source.slice(start));
  return { pattern: new RegExp('^' + pattern + '$', 'u'), keys, target };
}
function escapeRegex(value: string): string { return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }


function translateLine(message: string, language: RuntimeLanguage): string {
  const dictionary = language === 'en' ? frenchToEnglish : englishToFrench;
  const exact = dictionary.get(message);
  if (exact !== undefined) return exact;
  // Error objects are often converted to String() by file and renderer boundaries.
  const error = /^(Error|TypeError|RangeError|AbortError|DOMException):\s+([\s\S]+)$/u.exec(message);
  if (error) return `${error[1]}: ${translateLine(error[2], language)}`;
  const cached = /^([\s\S]+) · (memory|disk|miss)$/u.exec(message);
  if (cached) {
    const headline = translateLine(cached[1], language);
    if (headline !== cached[1]) return `${headline} · ${cached[2]}`;
  }
  for (const template of language === 'en' ? toEnglish : toFrench) {
    const match = template.pattern.exec(message);
    if (!match) continue;
    const values = Object.fromEntries(template.keys.map((key, index) => [key, match[index + 1]]));
    if (values.field) values.field = (language === 'en' ? fieldLabels : frenchFieldLabels).get(values.field) ?? values.field;
    if (values.reason) values.reason = translateLine(values.reason, language);
    return template.target.replace(/\{([a-zA-Z]+)\}/g, (_placeholder, key: string) => values[key]);
  }
  return message;
}

/** Translate presentation text only. Keep the original message in stored evidence and snapshots. */
export function translateRuntimeMessage(message: string, language: RuntimeLanguage = 'en'): string {
  if (!message) return message;
  // Preserve stack traces and source line endings while translating each known headline.
  return message.split(/(\r?\n)/u).map(line => /^(?:\r?\n)$/u.test(line) ? line : translateLine(line, language)).join('');
}


  projectJob<T>(request: unknown, transfer?: Transferable[]): Promise<T>;
  composeJob(request: unknown, transfer?: Transferable[]): Promise<{ settings: V2Settings; world?: World; mods: unknown[] }>;
  download(blob: Blob, name: string): void;
